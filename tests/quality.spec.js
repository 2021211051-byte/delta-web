import { test, expect } from '@playwright/test';

test('退出、帧数、无限弹药、投掷握持与切换开镜', async ({ page }) => {
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await page.waitForFunction(() => window.__ready && window.__deltaPortal?.assets, null, { timeout: 90000 });
  await expect(page.locator('#delta-room')).toBeHidden();
  await page.screenshot({ path: 'test-results/updated-home.png' });
  await page.locator('#delta-deploy').click();
  await page.waitForFunction(() => window.__G?.delta?.self, null, { timeout: 90000 });
  await expect(page.locator('#delta-fps')).toBeVisible();
  await expect.poll(() => page.locator('#delta-fps').textContent()).toContain('FPS');
  expect(await page.evaluate(() => window.__G.weapon.reserve)).toBe(Infinity);
  await expect(page.locator('.h-ammo-r')).toHaveText('∞');
  await page.locator('#view').click(); await page.waitForFunction(() => window.__G.input.locked);
  await page.keyboard.down('KeyG');
  await expect.poll(() => page.evaluate(() => window.__G.delta.equipment)).toBe('smoke');
  expect(await page.evaluate(() => window.__G.delta.latestProjectiles?.length || 0)).toBe(0);
  await page.keyboard.up('KeyG');
  await expect.poll(() => page.evaluate(() => window.__G.delta.latestProjectiles?.length)).toBe(1);
  await page.keyboard.press('Escape');
  await page.locator('.m-card[data-s="paused"] [data-act="settings"]').click();
  await page.locator('[data-act="ads-mode"]').click();
  await expect(page.locator('[data-act="ads-mode"]')).toHaveText('切换开镜');
  await page.locator('.m-card[data-s="paused"] [data-act="resume"]').click();
  await page.waitForFunction(() => window.__G.input.locked);
  await page.mouse.down({ button: 'right' }); await page.mouse.up({ button: 'right' });
  await page.waitForFunction(() => window.__G.input.ads === true);
  await page.mouse.down({ button: 'right' }); await page.mouse.up({ button: 'right' });
  await page.waitForFunction(() => window.__G.input.ads === false);
  await page.evaluate(() => { window.__G.player.pos.set(3, 0, 24.8); window.__G.player.yaw = Math.PI; });
  await page.keyboard.down('KeyW'); await page.keyboard.press('Space');
  await page.waitForFunction(() => window.__G.player.pos.z > 25.7 && window.__G.player.pos.y > .6, null, { timeout: 15000 });
  await page.keyboard.up('KeyW');
  await page.keyboard.press('Escape');
  await expect(page.locator('[data-act="lobby"]')).toBeVisible();
  await page.locator('[data-act="lobby"]').click();
  await page.waitForFunction(() => window.__deltaPortal?.mode === 'single', null, { timeout: 90000 });
  await expect(page.locator('#delta-portal')).toBeVisible();
  expect(errors).toEqual([]);
});
